with open(po_path, "rb") as f:
    catalog = pofile.read_po(f)

filled_count = 0
missing = []

for message in catalog:
    if not message.id:
        continue
    if message.id in translations:
        message.string = translations[message.id]
        filled_count += 1
    else:
        missing.append(message.id)

with open(po_path, "wb") as f:
    pofile.write_po(f, catalog, width=76)

print(f"DE .po updated: {filled_count} messages translated.")
if missing:
    print(f"Warning: {len(missing)} messages not found in translations dictionary:")
    for m in missing:
        print(" -", m)
else:
    print("All catalog messages are translated in DE!")
